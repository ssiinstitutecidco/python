# SQL : Structured Query Language
#  it is a standered language used to communicate with the dataabse.
# it is also used to store, retrieve , update, and manage data in relational databases ( like , Mysql, pstgreSQL, Oracle, SQL server)

# CateGories of Command :
# 1) DDL ( data definatiion language ) : it is used to define the structure of the databases.
#    CREATE, ALTER, DROP, TRUNCATE, RENAME

# 2) dml ( data manupulation language ) : it workswith the data inside the table
#   INSERT , UPDATE, DELETE

# 3) dql ( Data Query Language ) : it is used for fetching the data 
#    SELECT 

# 4) DCL ( data control language ) : it is used to control the access of the databases.
#    GRANT, REVOKE

# 5) TCL ( Transaction Control language ) : it is used to manage the transaction .
#   COMMIT  ROLLBACK  SAVEPOINT

